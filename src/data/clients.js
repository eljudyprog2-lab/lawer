export function createClientFromForm(form) {
  return {
    id: String(Date.now()),
    name: form.name.trim(),
    email: form.email.trim(),
    phone: form.phone.trim(),
    nationalId: form.nationalId.trim(),
    address: form.address.trim(),
    status: form.status || 'نشط',
    casesCount: 0,
    appointmentsCount: 0,
    balance: 0,
    registeredAt: new Date().toLocaleDateString('en-CA').replace(/-/g, '/'),
  }
}
