export function createLawyerFromForm(form) {
  return {
    id: String(Date.now()),
    name: form.name.trim(),
    email: form.email.trim(),
    phone: form.phone.trim(),
    nationalId: form.nationalId.trim(),
    barNumber: form.barNumber.trim(),
    specialization: form.specialization || '—',
    address: form.address.trim(),
    status: form.status || 'نشط',
    casesCount: 0,
    appointmentsCount: 0,
    notes: form.notes.trim(),
    registeredAt: new Date().toLocaleDateString('en-CA').replace(/-/g, '/'),
  }
}
